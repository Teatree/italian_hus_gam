// Regenerate scripts/big-cities.mjs (the candidate list used for the drive-time hint)
// from GeoNames' cities15000 dump.
//
//   node scripts/generate-big-cities.mjs
//
// The rule: population >= POP_MIN, in one of COUNTRIES, real places only (GeoNames feature
// class P, excluding PPLX — city *districts* like Madrid's Latina or Barcelona's Eixample,
// which the dump lists with district-level populations). Change the constants and re-run
// to move the threshold or add a country when properties from somewhere new appear.
//
// POP_MIN is deliberately LOW: this list is a candidate *net*, not a list of winners.
// drive-time.mjs scores candidates on drive time vs. prominence, so a small town only wins
// when it is much closer and nothing more important is in reach. That scoring needs two
// fields per row beyond the coordinates:
//   pop   — population, for the size part of the prominence bonus
//   fcode — GeoNames feature code, i.e. the administrative rank. This is the useful one:
//           PPLC national capital · PPLA regional capital · PPLA2 provincial capital
//           PPLA3 third-order seat · PPL no administrative role (a frazione or suburb).
//           In Italy a PPLA2 is where the hospital, courts and university are, which is
//           what makes it a better hint than a bigger-but-lesser town nearby.

import { execSync } from 'node:child_process';
import { writeFile, readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const POP_MIN = 20_000;
const COUNTRIES = ['IT', 'ES', 'FI'];
const DUMP_URL = 'https://download.geonames.org/export/dump/cities15000.zip';

// Districts/quarters of larger cities that GeoNames misclassifies as standalone cities
// (their feature code should be PPLX but isn't). Extend when a new one slips through.
const EXCLUDE_DISTRICTS = new Set([
  'Sant Martí', // Barcelona
  'Ciudad Lineal', // Madrid
  'Chamartín', // Madrid
  'Acilia-Castel Fusano-Ostia Antica', // Rome
  'Lido di Ostia', // Rome
  'Fuorigrotta', // Naples
  'Mestre', // Venice
]);

const tmp = await mkdtemp(join(tmpdir(), 'geonames-'));
try {
  console.log(`Downloading ${DUMP_URL} ...`);
  const res = await fetch(DUMP_URL);
  if (!res.ok) throw new Error(`GeoNames download failed: ${res.status}`);
  const zipPath = join(tmp, 'cities15000.zip');
  await writeFile(zipPath, Buffer.from(await res.arrayBuffer()));
  execSync(`tar -xf "${zipPath}" -C "${tmp}"`); // tar on Windows 10+ is bsdtar, which reads zip

  // TSV columns (geonames readme): 1 name, 4 lat, 5 lng, 6 feature class, 7 feature code,
  // 8 country code, 14 population.
  const cities = [];
  for (const line of (await readFile(join(tmp, 'cities15000.txt'), 'utf8')).split('\n')) {
    const f = line.split('\t');
    if (f.length < 15) continue;
    const pop = parseInt(f[14], 10) || 0;
    if (!COUNTRIES.includes(f[8]) || pop < POP_MIN) continue;
    if (f[6] !== 'P' || f[7] === 'PPLX' || EXCLUDE_DISTRICTS.has(f[1])) continue;
    cities.push({
      name: f[1],
      country: f[8],
      fcode: f[7],
      pop,
      coords: [+(+f[4]).toFixed(4), +(+f[5]).toFixed(4)],
    });
  }
  cities.sort((a, b) => a.country.localeCompare(b.country) || b.pop - a.pop);

  const rows = cities.map(
    (c) =>
      `  { name: ${JSON.stringify(c.name)}, country: '${c.country}', fcode: '${c.fcode}', pop: ${c.pop}, coords: [${c.coords[0]}, ${c.coords[1]}] },`,
  );
  const header =
    `// GENERATED by scripts/generate-big-cities.mjs — do not edit by hand, re-run the generator.\n` +
    `// Candidate places for the drive-time hint: GeoNames population >= ${POP_MIN.toLocaleString('en-US')} in\n` +
    `// ${COUNTRIES.join('/')}, city districts excluded. This is a candidate net, not a list of "big cities" —\n` +
    `// drive-time.mjs scores each on drive time vs. prominence (fcode rank + pop) and picks a winner.\n`;
  const outPath = join(dirname(fileURLToPath(import.meta.url)), 'big-cities.mjs');
  await writeFile(outPath, `${header}export const BIG_CITIES = [\n${rows.join('\n')}\n];\n`);

  const byCountry = COUNTRIES.map((cc) => `${cc} ${cities.filter((c) => c.country === cc).length}`).join(', ');
  console.log(`Wrote ${cities.length} cities (${byCountry}) to scripts/big-cities.mjs`);
} finally {
  await rm(tmp, { recursive: true, force: true });
}
